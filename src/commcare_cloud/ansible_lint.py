"""Run ansible-lint on commcare-cloud playbooks and roles.

Sets up the environment commcare-cloud's build_env() sets, so role and
collection references resolve, then runs ansible-lint from the repo root.
Arguments are passed through to ansible-lint; with no path argument it lints
the ansible directory::

    ansible-lint-cloud                    # check against .ansible-lint-ignore
    ansible-lint-cloud --generate-ignore  # regenerate .ansible-lint-ignore
"""
import importlib
import os
import sys
import tempfile

from commcare_cloud.environment.paths import (
    ANSIBLE_COLLECTIONS_PATH,
    ANSIBLE_DIR,
    ANSIBLE_ROLES_PATH,
)

# ANSIBLE_DIR is <repo>/src/commcare_cloud/ansible; the repo root is three
# levels up. Lint runs from there so reported paths (and the ignore file) are
# repo-relative.
REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(ANSIBLE_DIR)))
CONTENT_DIR = os.path.relpath(ANSIBLE_DIR, REPO_ROOT)
IGNORE_FILE = os.path.join(REPO_ROOT, ".ansible-lint-ignore")

IGNORE_HEADER = (
    "# DO NOT EDIT. Generated by ansible-lint-cloud --generate-ignore\n"
    "#\n"
    "# Violations that predate the upgrade to ansible-lint 26. Each line is\n"
    "# `<path> <rule> skip`, so a file listed here may have any number of\n"
    "# violations of that rule. Fix them, then regenerate this file.\n"
    "#\n"
    "# For a new exception, use an inline `# noqa: <rule>` at the task. Add one\n"
    "# here only when it can't be expressed inline, e.g. var-naming in a vars\n"
    "# file, and document the reason next to the relevant code.\n"
)


def main():
    os.environ["ANSIBLE_CONFIG"] = os.path.join(ANSIBLE_DIR, "ansible.cfg")
    # Include the local roles explicitly, so task files linted on their own
    # resolve roles the way playbooks do.
    os.environ["ANSIBLE_ROLES_PATH"] = os.pathsep.join(
        [os.path.join(ANSIBLE_DIR, "roles"), ANSIBLE_ROLES_PATH])
    os.environ["ANSIBLE_COLLECTIONS_PATH"] = ANSIBLE_COLLECTIONS_PATH
    # ansible-lint runs ansible-playbook and friends from the directory of
    # sys.executable with symlinks resolved. If that exact path isn't on PATH,
    # it adds it with a "PATH altered" warning. Add it here instead.
    bin_dir = os.path.realpath(os.path.dirname(sys.executable))
    os.environ["PATH"] = os.pathsep.join([bin_dir, os.environ.get("PATH", "")])
    os.chdir(REPO_ROOT)

    # ansible-lint loads its rule modules with `import_module(<file stem>)`
    # after appending the rules directory to sys.path. The `args` package
    # (a clint dependency) is earlier on sys.path, so `import args` gets it
    # instead of the args rule, and ansible-lint crashes. Pre-load the rule
    # module under that name.
    sys.modules["args"] = importlib.import_module("ansiblelint.rules.args")
    from ansiblelint.__main__ import _run_cli_entrypoint

    args = sys.argv[1:]
    if not any(os.path.exists(arg) for arg in args):
        args.append(CONTENT_DIR)
    if "--generate-ignore" not in args:
        sys.argv = ["ansible-lint", *args]
        _run_cli_entrypoint()
        return

    # ansible-lint leaves violations already skipped in the ignore file out of
    # the one it generates, so generate it against an empty ignore file.
    with tempfile.NamedTemporaryFile() as empty:
        sys.argv = ["ansible-lint", "--ignore-file", empty.name, *args]
        try:
            _run_cli_entrypoint()
        finally:
            skip_ignored()


def skip_ignored():
    """Add the `skip` qualifier to every entry in the generated ignore file.

    Without it, ansible-lint lists each ignored violation as a warning (and,
    in GitHub Actions, as an annotation), thousands of them.
    """
    with open(IGNORE_FILE) as fh:
        entries = [line.split() for line in fh if line.split('#')[0].strip()]
    with open(IGNORE_FILE, "w") as fh:
        fh.write(IGNORE_HEADER)
        for path, rule, *_ in entries:
            fh.write(f"{path} {rule} skip\n")


if __name__ == "__main__":
    main()
